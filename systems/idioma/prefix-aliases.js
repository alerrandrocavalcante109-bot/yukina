const normalized = Object.create(null);
const owners = new Map();
for (const [command, values] of Object.entries(aliases)) {
  normalized[command] = [...new Set(values.map(value => String(value).trim().toLowerCase())
    .filter(value => value && !/\s/.test(value)))].filter(alias => {
      const owner = owners.get(alias);
      if (owner && owner !== command) return false;
      owners.set(alias, command);
      return true;
    });
}

module.exports = Object.freeze(normalized);
